"""Generate server/modules/download/ytdlpOptionSpecs.js from yt-dlp's parser.

Run inside the Youtarr container so the specs match the yt-dlp it runs:

  docker exec -i youtarr-dev python3 - /opt/yt-dlp/yt-dlp \
    < scripts/generate-ytdlp-option-specs.py \
    > server/modules/download/ytdlpOptionSpecs.js

The argument is the yt-dlp zipapp (or source checkout) to import from.
"""
import sys

sys.path.insert(0, sys.argv[1])
from yt_dlp.options import create_parser  # noqa: E402
from yt_dlp.version import __version__  # noqa: E402


def collect_specs():
    parser = create_parser()
    by_option = {}
    for string, option in list(parser._long_opt.items()) + list(parser._short_opt.items()):
        entry = by_option.setdefault(id(option), {'option': option, 'strings': []})
        entry['strings'].append(string)

    specs = []
    for entry in by_option.values():
        option = entry['option']
        longs = [s for s in option._long_opts if parser._long_opt.get(s) is option]
        specs.append({
            'canonical': longs[0] if longs else entry['strings'][0],
            'strings': sorted(entry['strings']),
            'arity': option.nargs if option.takes_value() else 0,
        })
    specs.sort(key=lambda spec: spec['canonical'])
    return specs


def js_string(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main():
    lines = [
        '// GENERATED by scripts/generate-ytdlp-option-specs.py from yt-dlp '
        + __version__ + '. Do not edit by hand.',
        '//',
        '// Every yt-dlp option: canonical long name, all accepted spellings (long',
        '// aliases + short forms), and how many values it consumes. The allow / warn /',
        '// block policy for these lives in ytdlpOptionTable.js.',
        '',
        'const OPTION_SPECS = [',
    ]
    for spec in collect_specs():
        strings = ','.join(js_string(s) for s in spec['strings'])
        lines.append(
            f"  {{ canonical: {js_string(spec['canonical'])}, strings: [{strings}], arity: {spec['arity']} }},"
        )
    lines += ['];', '', 'module.exports = OPTION_SPECS;', '']
    sys.stdout.write('\n'.join(lines))


main()
